// Разбор фразы вида «йогурт 44 рубля» -> {title, amount, category}
(function (root) {
  const CATS = {
    'Продукты': ['йогурт','молок','хлеб','батон','сыр','мяс','колбас','сосиск','яблок','банан','овощ','фрукт','яйц','яиц','масл','кефир','творог','макарон','круп','рис','гречк','сахар','мук','вода','воду','сок','шоколад','конфет','печень','пирожн','торт','морожен','курица','курицу','куриц','рыб','помидор','огурц','картошк','картофел','лук','пятероч','магнит','перекрест','лент','ашан','вкусвилл','продукт','супермаркет','сметан','пельмен','орех','чипс','сметан','фарш','свинин','говядин','чай ','чая'],
    'Кафе и рестораны': ['кафе','ресторан','обед','ужин','завтрак','пицц','бургер','суши','ролл','шаурм','кофе','капучино','латте','макдон','кфс','бургер','столов','бар','доставк','еда','перекус','вкусно'],
    'Транспорт': ['такси','метро','автобус','бензин','заправк','проезд','парковк','маршрутк','трамва','электричк','поезд','самолет','авиабилет','яндекс го','убер','каршеринг','тройк','топлив','мойк'],
    'Жильё и ЖКХ': ['квартплат','коммунал','аренд','свет','электричеств','жкх','отоплен','ипотек','домофон','газ'],
    'Дом и быт': ['порошок','мыло','шампун','лампочк','посуд','ремонт','хозтовар','гель','салфетк','пакет','мебел','подушк','полотенц','губк','бумаг','швабр','инструмент'],
    'Здоровье': ['аптек','лекарств','таблетк','врач','стоматолог','анализ','витамин','больниц','клиник','массаж','очки','линз'],
    'Одежда и обувь': ['куртк','джинс','кроссовк','футболк','обув','одежд','ботинк','платье','свитер','шапк','носки','брюки','рубашк','пальто'],
    'Развлечения': ['кино','игр','театр','концерт','подписк','нетфликс','netflix','боулинг','бильярд','парк','музей','билет','стим','steam','ютуб','спотифай'],
    'Связь и интернет': ['телефон','связь','интернет','мобильн','симк','мтс','билайн','мегафон','теле2','тариф'],
    'Красота': ['парикмахер','стрижк','маникюр','косметик','крем','духи','помад','барбер','салон'],
    'Образование': ['книг','курс','школ','учебник','репетитор','универ','тетрад'],
    'Подарки': ['подарок','подарк','цветы','цветов','букет','открытк'],
    'Животные': ['корм','ветеринар','кошк','собак','наполнител','лоток'],
    'Прочее': []
  };
  const norm = s => s.toLowerCase().replace(/ё/g, 'е');

  const UNITS = {ноль:0,один:1,одна:1,одну:1,два:2,две:2,три:3,четыре:4,пять:5,шесть:6,семь:7,восемь:8,девять:9,десять:10,одиннадцать:11,двенадцать:12,тринадцать:13,четырнадцать:14,пятнадцать:15,шестнадцать:16,семнадцать:17,восемнадцать:18,девятнадцать:19};
  const TENS = {двадцать:20,тридцать:30,сорок:40,пятьдесят:50,шестьдесят:60,семьдесят:70,восемьдесят:80,девяносто:90};
  const HUND = {сто:100,двести:200,триста:300,четыреста:400,пятьсот:500,шестьсот:600,семьсот:700,восемьсот:800,девятьсот:900};
  function wordsToDigits(text) {
    const toks = text.split(/\s+/), out = [];
    let i = 0;
    while (i < toks.length) {
      const t = toks[i];
      const isNum = w => w in UNITS || w in TENS || w in HUND || /^тысяч/.test(w) || w === 'полтораста';
      if (!isNum(t)) { out.push(t); i++; continue; }
      let total = 0, cur = 0, j = i, used = false;
      while (j < toks.length && isNum(toks[j])) {
        const w = toks[j];
        if (/^тысяч/.test(w)) { total += (cur || 1) * 1000; cur = 0; }
        else cur += UNITS[w] ?? TENS[w] ?? HUND[w] ?? 0;
        used = true; j++;
      }
      if (used) out.push(String(total + cur));
      i = j;
    }
    return out.join(' ');
  }

  const CUR = /^(руб|рубл|р\.?$|₽|rub|копе)/;
  function parse(raw, learned) {
    learned = learned || {};
    let t = wordsToDigits(norm(raw).replace(/[«»"!?;:]/g, ' ').replace(/(\d)\s+(?=\d{3}\b)/g, '$1'));
    t = t.replace(/(\d),(\d)/g, '$1.$2').replace(/₽/g, ' ₽ ');
    const toks = t.split(/\s+/).filter(Boolean);
    let amount = null, idx = -1;
    // сначала число рядом с валютой, иначе первое число
    for (let i = 0; i < toks.length; i++) {
      if (/^\d+(\.\d+)?$/.test(toks[i]) && toks[i + 1] && CUR.test(toks[i + 1])) { amount = parseFloat(toks[i]); idx = i; break; }
    }
    if (idx < 0) for (let i = 0; i < toks.length; i++) {
      const m = toks[i].match(/^(\d+(\.\d+)?)(р|руб|₽)?\.?$/);
      if (m) { amount = parseFloat(m[1]); idx = i; break; }
    }
    const words = toks.filter((w, i) => i !== idx && !CUR.test(w) && !/^\d+(\.\d+)?$/.test(w) && !['за','на','потратил','потратила','купил','купила','заплатил','заплатила','расход','рублей'].includes(w));
    const title = words.join(' ').trim();
    return { amount, title: title ? title[0].toUpperCase() + title.slice(1) : '', category: categorize(words, learned) };
  }
  function categorize(words, learned) {
    for (const w of words) if (learned[w]) return learned[w];
    const score = {};
    for (const [cat, stems] of Object.entries(CATS)) for (const s of stems) {
      const st = s.trim();
      for (const w of words) if (w.startsWith(st)) score[cat] = (score[cat] || 0) + st.length;
    }
    const best = Object.entries(score).sort((a, b) => b[1] - a[1])[0];
    return best ? best[0] : 'Прочее';
  }
  root.Parser = { parse, categorize, CATS: Object.keys(CATS), norm };
  if (typeof module !== 'undefined') module.exports = root.Parser;
})(typeof window !== 'undefined' ? window : globalThis);
